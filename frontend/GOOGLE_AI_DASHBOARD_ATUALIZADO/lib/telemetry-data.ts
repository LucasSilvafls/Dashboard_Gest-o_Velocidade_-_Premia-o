export interface Incident {
  id: string;
  code: string;
  timestamp: string;
  date: string;
  time: string;
  hour?: number;
  plate: string;
  vehicleModel: string;
  vehicleCategory: string;
  excessType?: string;
  driver: string;
  ibutton: string;
  hasDriver: boolean;
  speedLimit: number;
  recordedSpeed: number;
  deltaSpeed: number;
  duration: string;
  durationSeconds: number;
  severity: 'BAIXA / LEVE' | 'MÉDIA / ALERTA' | 'ALTA / GRAVE';
  severityBand: 1 | 2 | 3 | 4; // 1: 1-10, 2: 11-20, 3: 21-30, 4: >30
  highway: string;
  city?: string;
  km: number;
  locationDetails: string;
  lat: number;
  lng: number;
  shift: 'Diurno' | 'Noturno';
  conciliationStatus?: 'PENDENTE' | 'CONCILIADO' | 'EM ANÁLISE';
  suggestedDriver?: {
    name: string;
    shift: string;
    confidence: number;
  };
}

export interface DriverScore {
  name: string;
  ibutton: string;
  plate: string;
  vehicleType: string;
  maxSpeed: number;
  limitSpeed: number;
  totalAlerts: number;
  violationsAbove80: number;
  worstEventLocation: string;
  hoursWorked: number;
  status: 'APTO' | 'INAPTO';
  deltaSpeed: number;
  rank: number;
}

export interface VehicleSummary {
  plate: string;
  model: string;
  category: 'PESADO' | 'BI-TREM' | 'LEVE';
  totalExcesses: number;
  maxSpeed: number;
  avgAboveLimit: number;
  highSeverityCount: number;
  mediumSeverityCount: number;
  lowSeverityCount: number;
  fleetSharePercent: number;
  criticalHighway: string;
  recentDrivers: {
    name: string;
    ibutton: string;
    lastSeen: string;
    excessesOnPlate: number;
    maxSpeed: number;
    complianceStatus: 'CONFORME' | 'ADVERTÊNCIA' | 'AUDITORIA CCO';
  }[];
}

